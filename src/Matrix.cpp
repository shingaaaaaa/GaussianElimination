#include "../include/Matrix.h"

/**
 * @brief Создаёт пустую матрицу с нулевыми размерностями.
 *
 *        После создания rows == 0, cols == 0, data пуста.
 *        Размерности заполняются функцией readMatrix после
 *        успешного разбора входного файла.
 */
Matrix::Matrix()
    // список инициализации — поля задаются ещё до выполнения тела конструктора
    // rows и cols обнуляем явно, чтобы они не содержали мусор из памяти
    // data инициализируется пустым вектором автоматически (у std::vector есть конструктор по умолчанию)
    : rows(0),
      cols(0),
      data()
{
}
