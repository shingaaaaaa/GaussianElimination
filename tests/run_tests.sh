#!/usr/bin/env bash

set -euo pipefail

# ── Путь к исполняемому файлу ────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP="${1:-${SCRIPT_DIR}/../build/src/app}"

if [[ ! -x "$APP" ]]; then
    echo "Ошибка: исполняемый файл не найден: $APP"
    echo "Соберите проект: cmake --build build"
    exit 1
fi

# ── Временная директория ─────────────────────────────────────────────────────
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ── Счётчики ─────────────────────────────────────────────────────────────────
PASS=0
FAIL=0
TOTAL=0

# ── Вспомогательные функции ───────────────────────────────────────────────────

# run_test <номер> <описание> <ожидаемый_код_возврата> <ожидаемый_вывод> <содержимое_входного_файла>
run_test() {
    local id="$1"
    local desc="$2"
    local expected_exit="$3"
    local expected_out="$4"
    local input_content="$5"

    TOTAL=$((TOTAL + 1))

    local in_file="${TMP}/in_${id}.txt"
    local out_file="${TMP}/out_${id}.txt"

    printf '%s' "$input_content" > "$in_file"

    local actual_exit=0
    "$APP" "$in_file" "$out_file" > /dev/null 2>&1 || actual_exit=$?

    local actual_out=""
    [[ -f "$out_file" ]] && actual_out="$(cat "$out_file")"

    if [[ "$actual_exit" -eq "$expected_exit" && "$actual_out" == "$expected_out" ]]; then
        printf "  \033[32mPASS\033[0m  [%03d] %s\n" "$id" "$desc"
        PASS=$((PASS + 1))
    else
        printf "  \033[31mFAIL\033[0m  [%03d] %s\n" "$id" "$desc"
        [[ "$actual_exit" != "$expected_exit" ]] && \
            printf "         exit: ожидался=%d получен=%d\n" "$expected_exit" "$actual_exit"
        [[ "$actual_out" != "$expected_out" ]] && \
            printf "         вывод: ожидался='%s' получен='%s'\n" "$expected_out" "$actual_out"
        FAIL=$((FAIL + 1))
    fi
}

# run_test_no_output — для случаев, когда файл вообще не должен создаваться
run_test_no_output() {
    local id="$1"
    local desc="$2"
    local input_content="$3"

    TOTAL=$((TOTAL + 1))

    local in_file="${TMP}/in_${id}.txt"
    local out_file="${TMP}/out_${id}.txt"

    printf '%s' "$input_content" > "$in_file"

    local actual_exit=0
    "$APP" "$in_file" "$out_file" > /dev/null 2>&1 || actual_exit=$?

    if [[ "$actual_exit" -eq 1 ]]; then
        printf "  \033[32mPASS\033[0m  [%03d] %s\n" "$id" "$desc"
        PASS=$((PASS + 1))
    else
        printf "  \033[31mFAIL\033[0m  [%03d] %s\n" "$id" "$desc"
        printf "         exit: ожидался=1 получен=%d\n" "$actual_exit"
        FAIL=$((FAIL + 1))
    fi
}

# ═════════════════════════════════════════════════════════════════════════════
echo ""
