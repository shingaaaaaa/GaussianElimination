/**
 * @file Error.h
 * @brief Описание перечисления ErrorType и класса Error,
 *        собирающего диагностическую информацию об ошибке во входных данных.
 */

#ifndef SLU_SOLVER_ERROR_H
#define SLU_SOLVER_ERROR_H

#include <string>

/**
 * @brief Тип ошибки, обнаруженной при чтении или валидации входных данных.
 *
 *        Значения сгруппированы по категориям:
 *        - файловые ошибки: inputFileNotExist, outputFileCreateFail;
 *        - ошибки структуры файла: emptyFile, unequalColumns, emptyLine, lineTooLong;
 *        - ошибки ограничений спецификации: tooFew/tooMany Rows/Cols;
 *        - ошибки числовых значений: nonNumericValue, tooManyDecimalPlaces,
 *          integerPartTooLong.
 */
enum class ErrorType
{
    inputFileNotExist,        ///< Входной файл не найден или нет прав на чтение.
    outputFileCreateFail,     ///< Не удаётся создать или открыть выходной файл.
    emptyFile,                ///< Входной файл не содержит ни одной строки.
    unequalColumns,           ///< Строки содержат разное количество столбцов.
    tooFewRows,               ///< Количество уравнений меньше допустимого (2).
    tooManyRows,              ///< Количество уравнений превышает допустимое (10).
    tooFewCols,               ///< Количество неизвестных меньше допустимого (2).
    tooManyCols,              ///< Количество неизвестных превышает допустимое (10).
    nonNumericValue,          ///< Лексема не является допустимым числом.
    tooManyDecimalPlaces,     ///< Число содержит более 3 знаков после запятой.
    integerPartTooLong,       ///< Целая часть числа содержит более 15 цифр.
    emptyLine,                ///< Строка файла пустая или состоит только из пробелов.
    lineTooLong               ///< Длина строки превышает 250 символов.
};

/**
 * @brief Описание одной ошибки, обнаруженной при обработке входного файла.
 *
 *        Класс хранит тип ошибки, некорректное значение (если применимо)
 *        и координаты (строка, столбец, длина строки) в исходном файле.
 *
 *        Метод generateErrorMessage() формирует читаемое сообщение
 *        с указанием позиции там, где это осмысленно.
 *
 * Пример использования:
 * @code
 *   Error e(ErrorType::nonNumericValue, "abc", 3, 2);
 *   std::cerr << e.generateErrorMessage() << std::endl;
 *   // → "Ошибка данных: Обнаружено нечисловое значение «abc». (строка: 3, столбец: 2)"
 * @endcode
 */
class Error
{
public:
    /// Тип обнаруженной ошибки.
    ErrorType type;

    /// Некорректное значение (токен) для диагностических сообщений.
    /// Пустая строка, если тип ошибки не связан с конкретным значением.
    std::string badValue;

    /// Номер строки в файле (нумерация с 1).
    /// Равен -1, если ошибка не привязана к конкретной строке.
    int row;

    /// Номер столбца — позиция токена в строке (нумерация с 1).
    /// Равен -1, если позиция столбца неприменима.
    int col;

    /// Фактическая длина строки в символах.
    /// Используется только для ErrorType::lineTooLong; иначе -1.
    int lineSize;

    /**
     * @brief Создаёт объект ошибки с полной инициализацией всех полей.
     *
     * @param errorType   Тип ошибки.
     * @param badValueStr Некорректное значение или пустая строка.
     * @param rowNumber   Номер строки в файле (с 1) или -1 по умолчанию.
     * @param colNumber   Номер столбца (с 1) или -1 по умолчанию.
     * @param lineLength  Фактическая длина строки или -1 по умолчанию.
     */
    Error(ErrorType errorType,
          const std::string& badValueStr = "",
          int rowNumber  = -1,
          int colNumber  = -1,
          int lineLength = -1);

    /**
     * @brief Формирует полное текстовое сообщение об ошибке для вывода.
     *
     *        Сообщение содержит описание ошибки и, для ошибок привязанных
     *        к конкретной позиции в файле, суффикс вида
     *        "(строка: N, столбец: M)".
     *
     * @return Строка, готовая для вывода в stderr.
     */
    std::string generateErrorMessage() const;
};

#endif // SLU_SOLVER_ERROR_H