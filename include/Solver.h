/**
 * @file Solver.h
 * @brief Публичный интерфейс модуля решения СЛАУ методом Гаусса-Жордана.
 *
 *        Содержит:
 *        - перечисление SolutionType — три возможных типа решения системы;
 *        - gaussianElimination     — основной алгоритм решения;
 *        - isValidNumber           — проверка лексемы на числовой формат;
 *        - formatNumber            — форматирование double для вывода;
 *        - readMatrix              — чтение и валидация входного файла;
 *        - writeResult             — запись результата в выходной файл.
 */

#ifndef SLU_SOLVER_SOLVER_H
#define SLU_SOLVER_SOLVER_H

#include <string>
#include <vector>

#include "Error.h"
#include "Matrix.h"

/**
 * @brief Тип решения системы линейных алгебраических уравнений.
 *
 *        Определяет один из трёх возможных исходов решения:
 *        - uniqueSolution         — система имеет ровно одно решение;
 *        - noSolutions            — система несовместна (нет решений);
 *        - infinitelyManySolutions — система имеет бесконечно много решений.
 */
enum class SolutionType
{
    uniqueSolution,           ///< Единственное решение x_1, ..., x_n.
    noSolutions,              ///< Нет решений (противоречивая система).
    infinitelyManySolutions   ///< Бесконечно много решений (система вырождена).
};

/**
 * @brief Решает систему линейных алгебраических уравнений методом
 *        Гаусса-Жордана с частичным выбором ведущего элемента.
 *
 *        Алгоритм выполняет прямой ход: для каждого столбца находит строку
 *        с максимальным по модулю элементом (частичный выбор), переставляет
 *        её на позицию ведущей, нормирует и обнуляет соответствующий столбец
 *        во всех остальных строках (включая расположенные выше).
 *
 *        После приведения матрицы к ступенчатому виду анализирует строки:
 *        строка [0 ... 0 | b ≠ 0] означает противоречие,
 *        нехватка ненулевых строк означает линейную зависимость.
 *
 * @param[in,out] matrix   Расширенная матрица [A|b]. Изменяется в процессе.
 * @param[out]    solution Вектор значений x_0..x_{n-1}.
 *                         Заполняется только при uniqueSolution.
 *                         При других результатах очищается.
 * @return Тип решения системы.
 */
SolutionType gaussianElimination(Matrix& matrix,
                                 std::vector<double>& solution);

/**
 * @brief Проверяет, является ли строка token допустимым числом.
 *
 *        Допустимый формат: [-]D{1..15}[.D{1..3}], где D — цифра.
 *        Строки вида ".5", "5.", "-", "+1", "1e2", "1.2.3" недопустимы.
 *
 * @param token Проверяемая лексема.
 * @return true  если token является допустимым числом,
 *         false в противном случае.
 */
bool isValidNumber(const std::string& token);

/**
 * @brief Форматирует вещественное число для записи в выходной файл.
 *
 *        Правила форматирования:
 *        - Если |value - round(value)| < 1e-9 — выводится целое без точки.
 *        - Иначе — выводится с тремя знаками после запятой,
 *          хвостовые нули и лишняя точка удаляются.
 *        - Значения -0.0 и значения в пределах 1e-9 от нуля → "0".
 *
 * @param value Число для форматирования.
 * @return Строковое представление числа.
 */
std::string formatNumber(double value);

/**
 * @brief Читает расширенную матрицу коэффициентов из текстового файла.
 *
 *        Функция считывает файл построчно, разбивает каждую строку
 *        на лексемы по пробелам и проверяет каждую лексему.
 *        Все найденные ошибки накапливаются в векторе errors —
 *        функция не прерывается на первой ошибке.
 *
 *        Проверяемые условия:
 *        - файл существует и доступен для чтения;
 *        - файл не пуст;
 *        - нет пустых строк;
 *        - нет строк длиннее 250 символов;
 *        - все лексемы являются допустимыми числами;
 *        - числа не нарушают ограничения на разрядность;
 *        - все строки содержат одинаковое число столбцов;
 *        - число уравнений от 2 до 10;
 *        - число неизвестных от 2 до 10.
 *
 * @param[in]  inputPath Путь к входному файлу.
 * @param[out] matrix    Заполненная матрица (при отсутствии ошибок).
 * @param[out] errors    Все обнаруженные ошибки с позициями.
 * @return true — файл успешно прочитан и матрица корректна;
 *         false — обнаружена хотя бы одна ошибка.
 */
bool readMatrix(const std::string& inputPath,
                Matrix& matrix,
                std::vector<Error>& errors);

/**
 * @brief Записывает результат решения системы в текстовый файл.
 *
 *        Форматы вывода в зависимости от типа решения:
 *        - uniqueSolution          → значения через пробел, например "1 -2 3.5"
 *        - noSolutions             → "no solutions"
 *        - infinitelyManySolutions → "infinitely many solutions"
 *
 * @param[in] outputPath Путь к выходному файлу (создаётся или перезаписывается).
 * @param[in] type       Тип найденного решения.
 * @param[in] solution   Вектор значений (используется только при uniqueSolution).
 * @return true  — файл успешно создан и записан;
 *         false — не удалось открыть файл на запись.
 */
bool writeResult(const std::string& outputPath,
                 SolutionType type,
                 const std::vector<double>& solution);

#endif // SLU_SOLVER_SOLVER_H