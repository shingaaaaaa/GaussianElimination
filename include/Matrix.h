/**
* @file Matrix.h
 * @brief Описание класса Matrix — расширенной матрицы системы уравнений.
 */

#ifndef SLU_SOLVER_MATRIX_H
#define SLU_SOLVER_MATRIX_H

#include <vector>

/**
 * @brief Расширенная матрица системы линейных алгебраических уравнений [A|b].
 *
 *        Элемент data[i][j] соответствует i-й строке и j-му столбцу.
 *        Последний столбец (индекс cols - 1) содержит свободные члены,
 *        поэтому выполняется: cols == (число неизвестных) + 1.
 *
 * Пример матрицы для системы:
 * @code
 *   2x + y = 5
 *   x - y  = 1
 * @endcode
 * будет представлена как:
 * @code
 *   data = {{2, 1, 5},
 *           {1,-1, 1}};
 *   rows = 2;
 *   cols = 3;
 * @endcode
 */
class Matrix
{
public:
    /// Количество строк матрицы (число уравнений в системе).
    int rows;

    /// Количество столбцов матрицы (число неизвестных + 1).
    int cols;

    /// Двумерный массив вещественных элементов расширенной матрицы.
    /// data[i] — i-я строка, data[i][j] — элемент строки i, столбца j.
    std::vector<std::vector<double>> data;

    /**
     * @brief Создаёт пустую матрицу: rows = 0, cols = 0, data пуста.
     *
     *        Все поля заполняются функцией readMatrix после
     *        успешного разбора входного файла.
     */
    Matrix();
};

#endif // SLU_SOLVER_MATRIX_H